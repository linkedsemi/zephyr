static int disk_vm_access_status(struct disk_info *disk)
{
	return DISK_STATUS_OK;
}

static int disk_vm_access_read(struct disk_info *disk, uint8_t *buff,
				uint32_t sector, uint32_t count)
{
	// Obtain an image via the network (the image may need to include the entire file system, not just an ISO file)
	uint8_t *image = (uint8_t *)image_iso;
	memcpy(buff, &image[sector * 512], count * 512);
	return 0;
}

static int disk_vm_access_write(struct disk_info *disk, const uint8_t *buff,
				 uint32_t sector, uint32_t count)
{
	return 0;
}

static int disk_vm_access_ioctl(struct disk_info *disk, uint8_t cmd, void *buff)
{
	switch (cmd) {
	case DISK_IOCTL_CTRL_SYNC:
		break;
	case DISK_IOCTL_GET_SECTOR_COUNT:
		*(uint32_t *)buff = 2048U; // block device sector count
		break;
	case DISK_IOCTL_GET_SECTOR_SIZE:
		*(uint32_t *)buff = 512U; // block device sector size
		break;
	case DISK_IOCTL_GET_ERASE_BLOCK_SZ:
		*(uint32_t *)buff  = 1U;
		break;
	case DISK_IOCTL_CTRL_INIT:
	case DISK_IOCTL_CTRL_DEINIT:
		break;
	default:
		return -EINVAL;
	}

	return 0;
}

static int disk_vm_access_init(struct disk_info *disk)
{
	return disk_vm_access_ioctl(disk, DISK_IOCTL_CTRL_INIT, NULL);
}

static int disk_vm_init(const struct device *dev)
{
	struct disk_info *info = dev->data;

	info->dev = dev;

	return disk_access_register(info);
}

static const struct disk_operations vm_disk_ops = {
	.init = disk_vm_access_init,
	.status = disk_vm_access_status,
	.read = disk_vm_access_read,
	.write = disk_vm_access_write,
	.ioctl = disk_vm_access_ioctl,
};

